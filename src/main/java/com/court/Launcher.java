package com.court;

/**
 * Plain main class that starts {@link Main}.
 * <p>
 * Run this class from IntelliJ/Eclipse when JavaFX is on the classpath: launching a
 * class that does not extend Application avoids the "JavaFX runtime components are
 * missing" error. With Maven, use {@code mvn javafx:run} instead.
 */
public class Launcher {

    public static void main(String[] args) {
        Main.main(args);
    }
}
